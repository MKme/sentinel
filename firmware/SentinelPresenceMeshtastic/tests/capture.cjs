const {chromium}=require('C:/GitHub/XTOC/xtoc-web/node_modules/playwright');
const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..'),repo=path.resolve(root,'../..');
const dir=path.join(repo,'assets/presence');fs.mkdirSync(dir,{recursive:true});
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1280,height:1000},deviceScaleFactor:1});
 await page.goto('file:///'+path.join(root,'.build/portal-preview/index.html').replaceAll('\\','/'));
 await page.getByRole('heading',{name:'SENTINEL',exact:true}).waitFor();
 if(await page.locator('select[name=meshChan]').inputValue()!=='1')throw Error('Wrong channel');
 if(await page.locator('input[name=motionPin]').inputValue()!=='3')throw Error('Wrong GPIO');
 if(await page.locator('[name=mavOut], [name=flightOn], [name=sentinelSource]').count())throw Error('Unexpected aircraft controls');
 await page.screenshot({path:path.join(dir,'setup-desktop.png'),fullPage:true});
 await page.locator('fieldset').filter({has:page.locator('legend',{hasText:'Companion observations'})}).screenshot({path:path.join(dir,'companion-setup.png')});
 await page.locator('fieldset').filter({has:page.locator('legend', {hasText:'Meshtastic output'})}).screenshot({path:path.join(dir,'mesh-output.png')});
 await page.setViewportSize({width:390,height:844});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');
 await page.screenshot({path:path.join(dir,'setup-mobile.png'),fullPage:true});
 await page.setViewportSize({width:1100,height:700});
 await page.goto('file:///'+path.join(root,'.build/portal-preview/saved.html').replaceAll('\\','/'));
 await page.getByRole('heading',{name:'Configuration saved'}).waitFor();
 await page.screenshot({path:path.join(dir,'saved.png')});
 await browser.close();console.log('Captured production portal renderer (simulated settings)');
})().catch(e=>{console.error(e);process.exit(1)});
